// Puts qlang.wasm (public/) and qlang.mjs (src/vendor/) in place.
//
//   npm run sync                      # download the release named in QLANG_VERSION
//   QLANG_REPO=../qlang npm run sync  # or take the files from a local build of qlang:
//                                     #   cargo build --profile wasm --target wasm32-unknown-unknown -p qlang-wasm
import fs from 'node:fs';
import path from 'node:path';
import GithubSlugger from 'github-slugger';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const wasmOut = path.join(root, 'public', 'qlang.wasm');
const mjsOut = path.join(root, 'src', 'vendor', 'qlang.mjs');
fs.mkdirSync(path.dirname(mjsOut), { recursive: true });
fs.mkdirSync(path.dirname(wasmOut), { recursive: true }); // git does not keep empty folders

let languageDoc;
let readme;
let intelSource;

if (process.env.QLANG_REPO) {
  const repo = path.resolve(root, process.env.QLANG_REPO);
  const wasm = path.join(repo, 'target/wasm32-unknown-unknown/wasm/qlang_wasm.wasm');
  if (!fs.existsSync(wasm)) {
    console.error(`${wasm} not found: build qlang-wasm first (see this script's header)`);
    process.exit(1);
  }
  fs.copyFileSync(wasm, wasmOut);
  fs.copyFileSync(path.join(repo, 'crates/qlang-wasm/js/qlang.mjs'), mjsOut);
  languageDoc = fs.readFileSync(path.join(repo, 'docs/language.md'), 'utf8');
  readme = fs.readFileSync(path.join(repo, 'README.md'), 'utf8');
  intelSource = fs.readFileSync(path.join(repo, 'editors/vscode/intel.js'), 'utf8');
  console.log(`qlang taken from ${repo}`);
} else {
  const version = fs.readFileSync(path.join(root, 'QLANG_VERSION'), 'utf8').trim();
  const base = `https://github.com/quenti77/qlang/releases/download/v${version}`;
  for (const [name, out] of [['qlang.wasm', wasmOut], ['qlang.mjs', mjsOut]]) {
    const res = await fetch(`${base}/${name}`);
    if (!res.ok) {
      console.error(`cannot download ${base}/${name}: ${res.status} (is there a release v${version} with ${name}?)`);
      process.exit(1);
    }
    fs.writeFileSync(out, Buffer.from(await res.arrayBuffer()));
  }
  const raw = async (file) => {
    const res = await fetch(`https://raw.githubusercontent.com/quenti77/qlang/v${version}/${file}`);
    if (!res.ok) {
      console.error(`cannot download ${file} of v${version}: ${res.status}`);
      process.exit(1);
    }
    return res.text();
  };
  languageDoc = await raw('docs/language.md');
  readme = await raw('README.md');
  intelSource = await raw('editors/vscode/intel.js');
  console.log(`qlang ${version} downloaded`);
}

// The hover and completion helpers of the VS Code extension (plain functions over the `info` the
// compiler reports), turned into an ES module: the editors of the site use them too.
fs.writeFileSync(
  path.join(root, 'src', 'vendor', 'intel.js'),
  `// generated by scripts/sync-qlang.mjs from editors/vscode/intel.js of qlang: do not edit\nconst module = { exports: {} };\n${intelSource}\nexport default module.exports;\n`
);

// The documentation pages generated from qlang's own documents (not committed):
// - docs/language.md, one page per chapter: the language;
// - README.md, a few sections: installation, usage, the JSON protocol…
// They go to content/<lang>/docs-generated/NN-name.md; the pages written for this site (the VS Code
// extension…) are in content/<lang>/docs/. The number in the name orders them all.
const slugify = (text) => new GithubSlugger().slug(text.replace(/`/g, ''));
// file names have no accents (the anchors inside the pages keep them, as the links to them do)
const ascii = (text) => text.normalize('NFD').replace(/[̀-ͯ]/g, '');
const plain = (title) => title.replace(/^\d+\.\s*/, '').replace(/`/g, '').trim();
const fileSlug = (number, title) => `${String(number).padStart(2, '0')}-${ascii(slugify(plain(title))).replace(/[^a-z0-9-]/g, '')}`.replace(/-+/g, '-').replace(/-$/, '');
const sections = (text) => text.split(/^(?=## )/m).filter((c) => c.startsWith('## '));
const titleOf = (chapter) => chapter.match(/^## (.*)$/m)[1];

// Per language: the sources (French: qlang's own documents; English: translations kept in
// content/en/reference/), the README sections to keep, the groups of the menu.
const LANGS = {
  fr: {
    contents: 'Sommaire',
    // the chapters of the language, split in groups by their number (10 + position in the document)
    languageGroups: [[10, 'Les fondamentaux'], [18, 'Types et objets'], [23, 'Bibliothèque standard'], [27, 'Référence']],
    readmeSections: [
      ['Installation', 1, 'Démarrer'],
      ['Utilisation', 2, 'Démarrer'],
      ['Protocole JSON', 31, 'Outils'],
      ['Navigateur : WebAssembly', 32, 'Outils'],
      ['Architecture', 40, 'Pour aller plus loin'],
      ['Développement', 41, 'Pour aller plus loin'],
    ],
  },
  en: {
    contents: 'Contents',
    languageGroups: [[10, 'Fundamentals'], [18, 'Types and objects'], [23, 'Standard library'], [27, 'Reference']],
    readmeSections: [
      ['Installation', 1, 'Getting started'],
      ['Usage', 2, 'Getting started'],
      ['JSON protocol', 31, 'Tools'],
      ['Browser: WebAssembly', 32, 'Tools'],
      ['Architecture', 40, 'Going further'],
      ['Development', 41, 'Going further'],
    ],
  },
};

function generate(lang, languageDoc, readme) {
const { readmeSections, contents, languageGroups } = LANGS[lang];
const languageGroup = (number) => languageGroups.findLast(([from]) => number >= from)[1];
const pages = [];
// the README: only these sections, in this order
const readmeChapters = sections(readme);
for (const [title, number, group] of readmeSections) {
  const chapter = readmeChapters.find((c) => titleOf(c) === title);
  if (!chapter) {
    console.error(`README.md has no section "${title}"`);
    process.exit(1);
  }
  pages.push({ slug: fileSlug(number, title), title: plain(title), chapter, group, source: 'readme' });
}
// the language: chapters 1..18 numbered 10..27
const body = languageDoc.replace(/^# .*\n/, '').replace(new RegExp(`^## ${contents}\\n[\\s\\S]*?(?=^## 1\\. )`, 'm'), '');
sections(body).forEach((chapter, i) => pages.push({ slug: fileSlug(10 + i, titleOf(chapter)), title: plain(titleOf(chapter)), chapter, group: languageGroup(10 + i), source: 'language' }));

// every anchor and the page it is in, to turn `](#anchor)` into links between pages
const anchors = new Map();
const chapterAnchors = new Set(); // chapter titles are page titles here: they have no anchor
for (const page of pages) {
  const seen = new GithubSlugger();
  for (const h of page.chapter.matchAll(/^#{2,4} (.*)$/gm)) {
    const anchor = seen.slug(h[1].replace(/`/g, ''));
    if (!anchors.has(anchor)) anchors.set(anchor, page.slug);
    if (h[0].startsWith('## ')) chapterAnchors.add(anchor);
  }
}
const pageOfLanguage = (anchor) => pages.find((p) => p.source === 'language' && p.slug === anchors.get(anchor));
const REPO = 'https://github.com/quenti77/qlang';

const outDir = path.join(root, 'content', lang, 'docs-generated');
fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });
for (const { slug, title, chapter, group } of pages) {
  let text = chapter
    .replace(/^## .*\n/, '') // the title is the page title
    .replace(/^(#{3,4}) /gm, (m, h) => h.slice(1) + ' ') // one level up
    .replace(/^```(\w*)$/gm, (m, lang) => `\u0000FENCE${lang}`)
    // links between pages
    .replace(/\]\(#([^)]+)\)/g, (m, anchor) => {
      if (!anchors.has(anchor)) return m;
      const target = anchors.get(anchor);
      if (chapterAnchors.has(anchor)) return `](../${target}/)`;
      return target === slug ? m : `](../${target}/#${anchor})`;
    })
    // the stability and migration documents are pages of the site
    .replace(/\]\((stability|migration)\.md\)/g, (m, f) => (f === 'stability' ? '](../97-stabilite/)' : '](../98-migration/)'))
    // links to the language reference, and to files of the repository
    .replace(/\]\(docs\/language\.md(?:#([^)]+))?\)/g, (m, anchor) => {
      const target = anchor && pageOfLanguage(anchor);
      return target ? `](../${target.slug}/${chapterAnchors.has(anchor) ? '' : '#' + anchor})` : `](../${pages.find((p) => p.source === 'language').slug}/)`;
    })
    .replace(/\]\(((?:(?:docs|crates|editors|scripts|examples)\/|\.\.\/(?!\d\d-))[^)#]*|[A-Z][A-Za-z.]+|qlang\.g4|install\.sh)(#[^)]*)?\)/g, (m, file, hash = '') => `](${REPO}/blob/main/${file.replace(/^\.\.\//, '')}${hash})`);
  // fences come in pairs: the opening one carries the language, the closing one is bare; code with no
  // language is qlang, shown highlighted but not runnable
  let open = false;
  text = text
    .split('\n')
    .map((line) => {
      const m = line.match(/^\u0000FENCE(\w*)$/);
      if (!m) return line;
      open = !open;
      return open ? '```' + (m[1] === '' ? 'qlang-ref' : m[1]) : '```';
    })
    .join('\n');
  fs.writeFileSync(path.join(outDir, `${slug}.md`), `---\ntitle: ${JSON.stringify(title)}\ngroup: ${JSON.stringify(group)}\n---\n\n# ${title}\n${text}`);
}
console.log(`documentation (${lang}): ${pages.length} pages generated`);
}

generate('fr', languageDoc, readme);
// the English text is a translation kept in content/en/reference/: warn when the French source has moved on
const countOf = (text, re) => (text.match(re) || []).length;
const enLanguage = fs.readFileSync(path.join(root, 'content', 'en', 'reference', 'language.md'), 'utf8');
for (const [what, re] of [['chapters', /^## \d+\. /gm], ['sections', /^### /gm], ['code blocks', /^```/gm]]) {
  const fr = countOf(languageDoc, re);
  const en = countOf(enLanguage, re);
  if (fr !== en) console.warn(`warning: docs/language.md has ${fr} ${what} in French and ${en} in content/en/reference/language.md: update the translation`);
}
const reference = (file) => fs.readFileSync(path.join(root, 'content', 'en', 'reference', file), 'utf8');
generate('en', reference('language.md'), reference('readme.md'));

// The reference of qlang-std: one page per module, from its API.md (the items) and the comment at the
// top of each file (the guide of the module). STD_VERSION names the tag; QLANG_STD_REPO takes a local clone.
const stdVersion = fs.readFileSync(path.join(root, 'STD_VERSION'), 'utf8').trim();
const stdRaw = async (file) => {
  if (process.env.QLANG_STD_REPO) return fs.readFileSync(path.join(path.resolve(root, process.env.QLANG_STD_REPO), file), 'utf8');
  const res = await fetch(`https://raw.githubusercontent.com/quenti77/qlang-std/v${stdVersion}/${file}`);
  if (!res.ok) {
    console.error(`cannot download ${file} of qlang-std v${stdVersion}: ${res.status}`);
    process.exit(1);
  }
  return res.text();
};
const stdApi = await stdRaw('API.md');
const stdModules = stdApi.split(/^(?=# [\w/.]+\.q$)/m).filter((m) => /^# [\w/.]+\.q$/m.test(m.split('\n')[0]));
const stdPages = [];
for (const [i, chunk] of stdModules.entries()) {
  const name = chunk.split('\n')[0].slice(2).trim();
  const source = await stdRaw(name);
  const header = source.match(/^--"([\s\S]*?)--"\n/);
  const guide = header ? header[1].replace(/^\s*# .*\n/, '').trim() : '';
  const items = chunk.split('\n').slice(1).join('\n').trim();
  stdPages.push({ name, slug: `${50 + i}-std-${name.replace(/\.q$/, '').replace(/[/.]/g, '-').replace(/_/g, '-')}`, guide, items });
}
const fence = (text) => {
  let open = false;
  return text
    .split('\n')
    .map((line) => {
      if (!/^```(\w*)$/.test(line)) return line;
      open = !open;
      return open ? '```' + (line.slice(3) === '' ? 'qlang-ref' : line.slice(3)) : '```';
    })
    .join('\n');
};
const STD_TEXT = {
  fr: { group: 'Bibliothèque standard (@std)', how: 'À importer avec', note: "Cette page vient du code de `qlang-std` : les commentaires sont en anglais.", items: 'Éléments' },
  en: { group: 'Standard library (@std)', how: 'Import with', note: 'This page comes from the code of `qlang-std`.', items: 'Items' },
};
for (const lang of ['fr', 'en']) {
  const t = STD_TEXT[lang];
  const outDir = path.join(root, 'content', lang, 'docs-generated');
  for (const page of stdPages) {
    const body = [
      `${t.how} \`import ... from "@std/${page.name}"\`. ${t.note}`,
      page.guide ? fence(page.guide) : '',
      page.items ? `## ${t.items}\n\n${fence(page.items.replace(/^## /gm, '### '))}` : '',
    ].filter(Boolean).join('\n\n');
    fs.writeFileSync(path.join(outDir, `${page.slug}.md`), `---\ntitle: ${JSON.stringify(page.name)}\ngroup: ${JSON.stringify(t.group)}\n---\n\n# ${page.name}\n\n${body}\n`);
  }
  console.log(`qlang-std ${stdVersion} (${lang}): ${stdPages.length} pages generated`);
}

// The reference of the prelude: what the language provides without an import (the global functions, the
// methods of the built-in types, `Hash.sha256`, the types of the prelude). `qlang doc --prelude` writes it as
// `reference.json`, attached to each release (from 0.80); QLANG_REFERENCE_JSON takes a local file. The examples
// are in reference/examples.txt: each one is RUN with the wasm of the site, and its output is shown.
{
  const referenceVersion = fs.readFileSync(path.join(root, 'QLANG_VERSION'), 'utf8').trim();
  let referenceText = null;
  if (process.env.QLANG_REFERENCE_JSON) {
    referenceText = fs.readFileSync(path.resolve(root, process.env.QLANG_REFERENCE_JSON), 'utf8');
  } else if (process.env.QLANG_REPO) {
    console.log('prelude reference skipped: set QLANG_REFERENCE_JSON to the output of `qlang doc --prelude`');
  } else {
    const res = await fetch(`https://github.com/quenti77/qlang/releases/download/v${referenceVersion}/reference.json`);
    if (res.ok) referenceText = await res.text();
    else console.log(`prelude reference skipped: qlang v${referenceVersion} has no reference.json (from 0.80)`);
  }
  if (referenceText) await generatePreludeReference(JSON.parse(referenceText));
}

async function generatePreludeReference(ref) {
  const { load } = await import('../src/vendor/qlang.mjs');
  const qlang = await load(fs.readFileSync(wasmOut));

  // reference/examples.txt: blocks that start with `@ owner.name`
  const examples = new Map();
  let current = null;
  for (const line of fs.readFileSync(path.join(root, 'reference', 'examples.txt'), 'utf8').split('\n')) {
    if (line.startsWith('@ ')) {
      current = { key: line.slice(2).trim(), lines: [] };
      examples.set(current.key, current);
    } else if (current) current.lines.push(line);
  }
  const problems = [];
  for (const ex of examples.values()) {
    ex.code = ex.lines.join('\n').trim() + '\n';
    const answer = qlang.handle({
      files: { 'main.q': ex.code },
      now: 1_700_000_000_000,
      seed: 1,
      limits: { max_steps: 5_000_000, max_depth: 250 },
    });
    if (!answer.ok) problems.push(`${ex.key}: ${answer.diagnostics.map((d) => `${d.code} ${d.message}`).join('; ')}`);
    ex.output = answer.output.replace(/\n$/, '');
  }
  if (problems.length) {
    console.error(`reference/examples.txt: ${problems.length} example(s) fail:\n  ${problems.join('\n  ')}`);
    process.exit(1);
  }
  const used = new Set();

  const TEXT = {
    fr: {
      group: 'Référence du prélude',
      intro: "Ce que le langage fournit sans `import`. Les explications et les signatures viennent du compilateur (`qlang doc --prelude`, version {v}) : elles sont en anglais, comme dans l'éditeur. Chaque exemple est exécuté à la génération du site : ce qu'il affiche est ce que fait vraiment qlang {v}.",
      prints: 'Affiche',
      methods: 'Méthodes',
      functions: 'Fonctions',
      fields: 'Champs',
      variants: 'Variantes',
      global: 'Fonctions globales',
    },
    en: {
      group: 'Prelude reference',
      intro: 'What the language provides without an `import`. The explanations and signatures come from the compiler (`qlang doc --prelude`, version {v}), the same as in the editor. Every example is run when the site is built: what it prints is what qlang {v} really does.',
      prints: 'Prints',
      methods: 'Methods',
      functions: 'Functions',
      fields: 'Fields',
      variants: 'Variants',
      global: 'Global functions',
    },
  };

  const exampleOf = (key) => {
    const ex = examples.get(key);
    if (!ex) return '';
    used.add(key);
    return { code: ex.code, output: ex.output };
  };
  // one entry: heading, signature, explanation, example with its output
  const entry = (t, key, e, level = '###') => {
    const lines = [`${level} ${e.name}`, '', '```qlang-ref', e.signature, '```'];
    if (e.doc) lines.push('', e.doc);
    const ex = exampleOf(key);
    if (ex) {
      lines.push('', '```qlang-ref', ex.code.trimEnd(), '```', '', `${t.prints}:`, '', '```', ex.output, '```');
    }
    return lines.join('\n');
  };

  const pages = [];
  pages.push({ name: 'functions', title: 'print, panic, assert…', body: (t) => ref.functions.map((f) => entry(t, f.name, f)).join('\n\n') });
  const mergedNamespaces = new Set(ref.builtin.map((b) => b.name));
  for (const b of ref.builtin) {
    const ns = ref.namespaces.find((n) => n.name === b.name);
    pages.push({
      name: b.name,
      title: b.name,
      body: (t) => {
        const parts = [];
        if (ns) {
          parts.push(`## ${t.functions}`, ns.entries.map((e) => entry(t, `${b.name}.${e.name}`, e)).join('\n\n'));
        }
        if (b.methods.length) parts.push(`## ${t.methods}`, b.methods.map((m) => entry(t, `${b.name}.${m.name}`, m)).join('\n\n'));
        return parts.join('\n\n');
      },
    });
  }
  for (const n of ref.namespaces.filter((n) => !mergedNamespaces.has(n.name))) {
    pages.push({ name: n.name, title: n.name, body: (t) => n.entries.map((e) => entry(t, `${n.name}.${e.name}`, e)).join('\n\n') });
  }
  for (const ty of ref.types.filter((x) => !mergedNamespaces.has(x.name))) {
    pages.push({
      name: ty.name,
      title: ty.name,
      body: (t) => {
        const parts = [];
        if (ty.doc) parts.push(ty.doc);
        if (ty.variants.length) parts.push(`## ${t.variants}`, ty.variants.map((v) => `- \`${v.signature}\`${v.doc ? ` — ${v.doc}` : ''}`).join('\n'));
        if (ty.fields.length) parts.push(`## ${t.fields}`, ty.fields.map((f) => `- \`${f.signature}\`${f.doc ? ` — ${f.doc}` : ''}`).join('\n'));
        if (ty.methods.length) parts.push(`## ${t.methods}`, ty.methods.map((m) => entry(t, `${ty.name}.${m.name}`, m)).join('\n\n'));
        return parts.join('\n\n');
      },
    });
  }
  for (const lang of ['fr', 'en']) {
    const t = TEXT[lang];
    const outDir = path.join(root, 'content', lang, 'docs-generated');
    for (const old of fs.readdirSync(outDir)) if (/^1\d\d-ref-/.test(old)) fs.unlinkSync(path.join(outDir, old));
    pages.forEach((page, i) => {
      const slug = `${100 + i}-ref-${page.name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`;
      const body = [t.intro.replaceAll('{v}', ref.version), page.body(t)].filter(Boolean).join('\n\n');
      fs.writeFileSync(path.join(outDir, `${slug}.md`), `---\ntitle: ${JSON.stringify(page.title)}\ngroup: ${JSON.stringify(t.group)}\n---\n\n# ${page.title}\n\n${body}\n`);
    });
    console.log(`prelude reference ${ref.version} (${lang}): ${pages.length} pages generated`);
  }
  const unused = [...examples.keys()].filter((k) => !used.has(k));
  if (unused.length) {
    console.error(`reference/examples.txt: no such function for ${unused.join(', ')}`);
    process.exit(1);
  }
  const total = ref.functions.length + ref.builtin.reduce((n, b) => n + b.methods.length, 0) + ref.namespaces.reduce((n, x) => n + x.entries.length, 0);
  console.log(`prelude reference: ${used.size} of ${total} functions and methods have an example`);
}
